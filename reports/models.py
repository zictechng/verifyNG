import uuid
from datetime import timedelta
from django.db import models
from django.utils import timezone
from users.models import User
from identities.models import SubjectEntity


class FraudReport(models.Model):
    public_id = models.UUIDField(
        default=uuid.uuid4,
        editable=False,
        unique=True,
        db_index=True,
        help_text="Public-facing report identifier — never expose the integer PK"
    )
    STATES = (
        ('submitted', 'Submitted'),
        ('under_review', 'Under Review'),
        ('published', 'Published'),
        ('disputed', 'Disputed'),
        ('resolved', 'Resolved'),
        ('rejected', 'Rejected'),
        ('restricted', 'Restricted'),
        ('archived', 'Archived'),
    )

    reference_number = models.CharField(
        max_length=50,
        unique=True,
        db_index=True,
        default='VNG-PENDING',
        help_text="Public reference tracking ID generated by service layer"
    )
    reporter = models.ForeignKey(
        User,
        on_delete=models.SET_NULL,
        null=True,
        related_name='submitted_reports'
    )
    target_subject = models.ForeignKey(
        SubjectEntity,
        on_delete=models.PROTECT,
        related_name='reports'
    )
    title = models.CharField(
        max_length=255,
        default='Allegation Report'
    )
    allegation = models.TextField(
        help_text="Detailed description of alleged incident"
    )
    incident_date = models.DateField(
        null=True,
        blank=True
    )
    state = models.CharField(
        max_length=20,
        choices=STATES,
        default='submitted',
        db_index=True
    )
    moderation_notes = models.TextField(
        blank=True,
        help_text="Internal moderation data; must not be exposed in public API responses"
    )
    created_at = models.DateTimeField(
        default=timezone.now
    )
    updated_at = models.DateTimeField(
        auto_now=True
    )

    class Meta:
        verbose_name = 'Fraud Report'
        verbose_name_plural = 'Fraud Reports'
        ordering = ['-created_at']

    def __str__(self):
        return f"[{self.reference_number}] {self.title} - {self.get_state_display()}"

    @property
    def is_misconduct(self):
        title_str = self.title or ''
        allegation_str = self.allegation or ''
        return (
            title_str.startswith('Staff Misconduct') or
            allegation_str.startswith('WORKPLACE MISCONDUCT REPORT')
        )

    @property
    def suspect_context(self):
        """Extracts submitted suspect context from the initial audit log."""
        if not self.pk:
            return {}
        init_log = self.audit_logs.filter(action="REPORT_SUBMITTED").first()
        if init_log and isinstance(init_log.details, dict):
            return init_log.details.get('suspect_context', {})
        return {}

    @property
    def suspect_email(self):
        """Returns the email address of the accused person or entity."""
        ctx = self.suspect_context
        if ctx.get('email'):
            return ctx['email']
        if hasattr(self.target_subject, 'business_profile') and self.target_subject.business_profile.contact_email:
            return self.target_subject.business_profile.contact_email
        return None

    @property
    def suspect_phone(self):
        """Returns the phone number of the accused person or entity."""
        ctx = self.suspect_context
        if ctx.get('phone'):
            return ctx['phone']
        if hasattr(self.target_subject, 'business_profile') and self.target_subject.business_profile.contact_phone:
            return self.target_subject.business_profile.contact_phone
        return None

    @property
    def dispute_deadline(self):
        """The 7-day fair-hearing / right-of-response expiration date."""
        ctx = self.suspect_context
        if ctx.get('dispute_deadline'):
            return ctx['dispute_deadline']
        base_time = self.created_at or timezone.now()
        return (base_time + timedelta(days=7)).strftime('%d %B %Y')

    @property
    def is_within_dispute_window(self):
        """Returns True if within the 7-day fair-hearing window."""
        base_time = self.created_at or timezone.now()
        return timezone.now() <= (base_time + timedelta(days=7))

    @property
    def complainant_rebuttal(self):
        """Returns the formal rebuttal statement and evidence submitted by the complainant, if any."""
        if not self.pk:
            return None
        log = self.audit_logs.filter(action="COMPLAINANT_REBUTTAL_SUBMITTED").first()
        if log and isinstance(log.details, dict):
            details_dict = dict(log.details)
            return {
                'statement': log.details.get('rebuttal_statement', ''),
                'rebuttal_statement': log.details.get('rebuttal_statement', ''),
                'submitted_at': log.timestamp,
                'timestamp': log.timestamp,
                'evidence_id': log.details.get('evidence_id'),
                'evidence_name': log.details.get('evidence_name', ''),
                'actor': log.performed_by,
                'details': details_dict,
                'log': log,
            }
        return None

    @property
    def can_submit_rebuttal(self):
        """Returns True if complainant can submit their 1-time rebuttal."""
        return (
            self.state == 'disputed'
            and self.disputes.exists()
            and self.complainant_rebuttal is None
        )

    @property
    def are_pleadings_closed(self):
        """Pleadings close when complainant submits final rebuttal or report reaches final decision."""
        return self.complainant_rebuttal is not None or self.state in ('resolved', 'dismissed', 'closed', 'rejected')

    @property
    def moderator_info_requests(self):
        """Returns all interlocutory information requests issued by compliance moderators."""
        if not self.pk:
            return []
        return self.audit_logs.filter(action="MODERATOR_INFO_REQUEST").order_by('-timestamp')

    def pending_info_request_for_user(self, user):
        """Checks if a specific user has an active, unfulfilled info request."""
        if not user or not user.is_authenticated or not self.pk:
            return None
        is_reporter = (self.reporter_id == user.id)
        is_respondent = self.disputes.filter(disputant=user).exists()
        if not is_respondent and self.suspect_email and user.email:
            is_respondent = (self.suspect_email.strip().lower() == user.email.strip().lower())

        for req in self.moderator_info_requests:
            details = req.details or {}
            if details.get('status') == 'pending':
                target_role = details.get('target_role')
                if (target_role == 'complainant' and is_reporter) or (target_role == 'respondent' and is_respondent):
                    return req
        return None


class ReportEvidence(models.Model):
    EVIDENCE_TYPES = (
        ('document', 'Document/PDF'),
        ('screenshot', 'Screenshot/Image'),
        ('receipt', 'Payment Receipt'),
        ('chat_log', 'Chat Log'),
        ('other', 'Other Evidence'),
    )

    report = models.ForeignKey(
        FraudReport,
        on_delete=models.PROTECT,
        related_name='evidence_files'
    )
    file = models.FileField(
        upload_to='evidence/%Y/%m/',
        help_text="Evidence file; security/privacy controls applied in Phase 5"
    )
    file_type = models.CharField(
        max_length=20,
        choices=EVIDENCE_TYPES,
        default='screenshot'
    )
    description = models.CharField(
        max_length=255,
        blank=True
    )
    is_confidential = models.BooleanField(
        default=True,
        help_text="Confidential evidence accessible only to authorized moderators"
    )
    storage_provider = models.CharField(
        max_length=50,
        default='local',
        blank=True,
        help_text="Storage provider identifier ('local', 'cloudinary', 's3')"
    )
    storage_public_id = models.CharField(
        max_length=255,
        blank=True,
        help_text="Cloud provider public ID / storage key"
    )
    storage_resource_type = models.CharField(
        max_length=20,
        blank=True,
        help_text="Cloud provider resource type ('image', 'raw')"
    )
    storage_format = models.CharField(
        max_length=20,
        blank=True,
        help_text="File extension / format ('pdf', 'png', 'docx')"
    )
    uploaded_at = models.DateTimeField(
        default=timezone.now
    )

    class Meta:
        verbose_name = 'Report Evidence'
        verbose_name_plural = 'Report Evidence'

    def __str__(self):
        return f"Evidence ({self.get_file_type_display()}) for {self.report.reference_number}"


class Dispute(models.Model):
    public_id = models.UUIDField(
        default=uuid.uuid4,
        editable=False,
        unique=True,
        db_index=True,
        help_text="Public-facing dispute identifier — never expose the integer PK"
    )
    DISPUTE_STATES = (
        ('opened', 'Opened'),
        ('under_review', 'Under Review'),
        ('accepted', 'Accepted (Report Removed/Restricted)'),
        ('rejected', 'Rejected (Report Retained)'),
    )

    report = models.ForeignKey(
        FraudReport,
        on_delete=models.PROTECT,
        related_name='disputes'
    )
    disputant = models.ForeignKey(
        User,
        on_delete=models.SET_NULL,
        null=True,
        related_name='submitted_disputes'
    )
    reason = models.TextField(
        help_text="Statement explaining why allegation is disputed"
    )
    counter_evidence = models.FileField(
        upload_to='disputes/%Y/%m/',
        blank=True,
        null=True,
        help_text="Primary dispute evidence file; multiple attachments deferred to future refinement"
    )
    status = models.CharField(
        max_length=20,
        choices=DISPUTE_STATES,
        default='opened',
        db_index=True
    )
    resolution_notes = models.TextField(
        blank=True
    )
    created_at = models.DateTimeField(
        default=timezone.now
    )
    resolved_at = models.DateTimeField(
        null=True,
        blank=True
    )

    class Meta:
        verbose_name = 'Dispute'
        verbose_name_plural = 'Disputes'
        ordering = ['-created_at']

    def __str__(self):
        return f"Dispute for {self.report.reference_number} ({self.get_status_display()})"

    @property
    def complainant_rebuttal(self):
        """Returns the complainant's final rebuttal statement & counter-proof from the parent report, if submitted."""
        return self.report.complainant_rebuttal if self.report else None


class AuditLog(models.Model):
    """
    Single platform-wide immutable audit trail.
    Covers all admin actions, user actions, verification events,
    payment events, authentication events, and system events.
    Append-only — never delete or update rows.
    """

    ACTION_TYPE_CHOICES = (
        ('AUTH',         'Authentication'),
        ('USER_MGMT',    'User Management'),
        ('REPORT',       'Fraud Report'),
        ('VERIFICATION', 'Verification'),
        ('PAYMENT',      'Payment'),
        ('ADMIN',        'Admin Action'),
        ('SYSTEM',       'System Event'),
        ('GENERAL',      'General'),
    )

    # What type of action
    action_type = models.CharField(
        max_length=30,
        choices=ACTION_TYPE_CHOICES,
        default='GENERAL',
        db_index=True,
    )

    # The human-readable action name, e.g. "USER_SUSPENDED", "REPORT_APPROVED"
    action = models.CharField(max_length=255)

    # Who did it
    performed_by = models.ForeignKey(
        User,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='audit_logs_performed',
    )

    # Who it was done to (optional — for user management actions)
    target_user = models.ForeignKey(
        User,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='audit_logs_as_target',
    )

    # Linked report (optional — for report-related actions)
    report = models.ForeignKey(
        FraudReport,
        on_delete=models.PROTECT,
        null=True,
        blank=True,
        related_name='audit_logs',
    )

    # Request context
    ip_address = models.GenericIPAddressField(null=True, blank=True)
    url_path = models.CharField(max_length=500, blank=True, default='')
    http_method = models.CharField(max_length=10, blank=True, default='')
    user_agent = models.TextField(blank=True, default='')

    # Device / browser context (parsed from user_agent)
    device_type = models.CharField(max_length=50, blank=True, default='')
    browser = models.CharField(max_length=80, blank=True, default='')
    os = models.CharField(max_length=80, blank=True, default='')

    # Location context
    location_country = models.CharField(max_length=100, blank=True, default='')
    location_city = models.CharField(max_length=100, blank=True, default='')

    # Flexible extra data (old field — keep for backward compat)
    details = models.JSONField(default=dict, blank=True)

    timestamp = models.DateTimeField(default=timezone.now, db_index=True)

    @property
    def created_at(self):
        """Backward-compatible alias for timestamp."""
        return self.timestamp

    class Meta:
        verbose_name = 'Audit Log'
        verbose_name_plural = 'Audit Logs'
        ordering = ['-timestamp']
        indexes = [
            models.Index(fields=['action_type', 'timestamp'], name='auditlog_type_ts_idx'),
        ]

    def __str__(self):
        actor = self.performed_by.username if self.performed_by else 'system'
        return f"[{self.action_type}] {self.action} by {actor} at {self.timestamp:%Y-%m-%d %H:%M}"



