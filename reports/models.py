from django.db import models
from django.utils import timezone
from users.models import User
from identities.models import SubjectEntity


class FraudReport(models.Model):
    STATES = (
        ('submitted', 'Submitted'),
        ('under_review', 'Under Review'),
        ('published', 'Published'),
        ('disputed', 'Disputed'),
        ('resolved', 'Resolved'),
        ('rejected', 'Rejected'),
        ('restricted', 'Restricted'),
        ('archived', 'Archived'),
    )

    reference_number = models.CharField(
        max_length=50,
        unique=True,
        db_index=True,
        default='VNG-PENDING',
        help_text="Public reference tracking ID generated by service layer"
    )
    reporter = models.ForeignKey(
        User,
        on_delete=models.SET_NULL,
        null=True,
        related_name='submitted_reports'
    )
    target_subject = models.ForeignKey(
        SubjectEntity,
        on_delete=models.PROTECT,
        related_name='reports'
    )
    title = models.CharField(
        max_length=255,
        default='Allegation Report'
    )
    allegation = models.TextField(
        help_text="Detailed description of alleged incident"
    )
    incident_date = models.DateField(
        null=True,
        blank=True
    )
    state = models.CharField(
        max_length=20,
        choices=STATES,
        default='submitted',
        db_index=True
    )
    moderation_notes = models.TextField(
        blank=True,
        help_text="Internal moderation data; must not be exposed in public API responses"
    )
    created_at = models.DateTimeField(
        default=timezone.now
    )
    updated_at = models.DateTimeField(
        auto_now=True
    )

    class Meta:
        verbose_name = 'Fraud Report'
        verbose_name_plural = 'Fraud Reports'
        ordering = ['-created_at']

    def __str__(self):
        return f"[{self.reference_number}] {self.title} - {self.get_state_display()}"


class ReportEvidence(models.Model):
    EVIDENCE_TYPES = (
        ('document', 'Document/PDF'),
        ('screenshot', 'Screenshot/Image'),
        ('receipt', 'Payment Receipt'),
        ('chat_log', 'Chat Log'),
        ('other', 'Other Evidence'),
    )

    report = models.ForeignKey(
        FraudReport,
        on_delete=models.PROTECT,
        related_name='evidence_files'
    )
    file = models.FileField(
        upload_to='evidence/%Y/%m/',
        help_text="Evidence file; security/privacy controls applied in Phase 5"
    )
    file_type = models.CharField(
        max_length=20,
        choices=EVIDENCE_TYPES,
        default='screenshot'
    )
    description = models.CharField(
        max_length=255,
        blank=True
    )
    is_confidential = models.BooleanField(
        default=True,
        help_text="Confidential evidence accessible only to authorized moderators"
    )
    storage_provider = models.CharField(
        max_length=50,
        default='local',
        blank=True,
        help_text="Storage provider identifier ('local', 'cloudinary', 's3')"
    )
    storage_public_id = models.CharField(
        max_length=255,
        blank=True,
        help_text="Cloud provider public ID / storage key"
    )
    storage_resource_type = models.CharField(
        max_length=20,
        blank=True,
        help_text="Cloud provider resource type ('image', 'raw')"
    )
    storage_format = models.CharField(
        max_length=20,
        blank=True,
        help_text="File extension / format ('pdf', 'png', 'docx')"
    )
    uploaded_at = models.DateTimeField(
        default=timezone.now
    )

    class Meta:
        verbose_name = 'Report Evidence'
        verbose_name_plural = 'Report Evidence'

    def __str__(self):
        return f"Evidence ({self.get_file_type_display()}) for {self.report.reference_number}"


class Dispute(models.Model):
    DISPUTE_STATES = (
        ('opened', 'Opened'),
        ('under_review', 'Under Review'),
        ('accepted', 'Accepted (Report Removed/Restricted)'),
        ('rejected', 'Rejected (Report Retained)'),
    )

    report = models.ForeignKey(
        FraudReport,
        on_delete=models.PROTECT,
        related_name='disputes'
    )
    disputant = models.ForeignKey(
        User,
        on_delete=models.SET_NULL,
        null=True,
        related_name='submitted_disputes'
    )
    reason = models.TextField(
        help_text="Statement explaining why allegation is disputed"
    )
    counter_evidence = models.FileField(
        upload_to='disputes/%Y/%m/',
        blank=True,
        null=True,
        help_text="Primary dispute evidence file; multiple attachments deferred to future refinement"
    )
    status = models.CharField(
        max_length=20,
        choices=DISPUTE_STATES,
        default='opened',
        db_index=True
    )
    resolution_notes = models.TextField(
        blank=True
    )
    created_at = models.DateTimeField(
        default=timezone.now
    )
    resolved_at = models.DateTimeField(
        null=True,
        blank=True
    )

    class Meta:
        verbose_name = 'Dispute'
        verbose_name_plural = 'Disputes'
        ordering = ['-created_at']

    def __str__(self):
        return f"Dispute for {self.report.reference_number} ({self.get_status_display()})"


class AuditLog(models.Model):
    """
    Single platform-wide immutable audit trail.
    Covers all admin actions, user actions, verification events,
    payment events, authentication events, and system events.
    Append-only — never delete or update rows.
    """

    ACTION_TYPE_CHOICES = (
        ('AUTH',         'Authentication'),
        ('USER_MGMT',    'User Management'),
        ('REPORT',       'Fraud Report'),
        ('VERIFICATION', 'Verification'),
        ('PAYMENT',      'Payment'),
        ('ADMIN',        'Admin Action'),
        ('SYSTEM',       'System Event'),
        ('GENERAL',      'General'),
    )

    # What type of action
    action_type = models.CharField(
        max_length=30,
        choices=ACTION_TYPE_CHOICES,
        default='GENERAL',
        db_index=True,
    )

    # The human-readable action name, e.g. "USER_SUSPENDED", "REPORT_APPROVED"
    action = models.CharField(max_length=255)

    # Who did it
    performed_by = models.ForeignKey(
        User,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='audit_logs_performed',
    )

    # Who it was done to (optional — for user management actions)
    target_user = models.ForeignKey(
        User,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='audit_logs_as_target',
    )

    # Linked report (optional — for report-related actions)
    report = models.ForeignKey(
        FraudReport,
        on_delete=models.PROTECT,
        null=True,
        blank=True,
        related_name='audit_logs',
    )

    # Request context
    ip_address = models.GenericIPAddressField(null=True, blank=True)
    url_path = models.CharField(max_length=500, blank=True, default='')
    http_method = models.CharField(max_length=10, blank=True, default='')
    user_agent = models.TextField(blank=True, default='')

    # Device / browser context (parsed from user_agent)
    device_type = models.CharField(max_length=50, blank=True, default='')
    browser = models.CharField(max_length=80, blank=True, default='')
    os = models.CharField(max_length=80, blank=True, default='')

    # Location context
    location_country = models.CharField(max_length=100, blank=True, default='')
    location_city = models.CharField(max_length=100, blank=True, default='')

    # Flexible extra data (old field — keep for backward compat)
    details = models.JSONField(default=dict, blank=True)

    timestamp = models.DateTimeField(default=timezone.now, db_index=True)

    class Meta:
        verbose_name = 'Audit Log'
        verbose_name_plural = 'Audit Logs'
        ordering = ['-timestamp']
        indexes = [
            models.Index(fields=['action_type', 'timestamp'], name='auditlog_type_ts_idx'),
        ]

    def __str__(self):
        actor = self.performed_by.username if self.performed_by else 'system'
        return f"[{self.action_type}] {self.action} by {actor} at {self.timestamp:%Y-%m-%d %H:%M}"



