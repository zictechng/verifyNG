def number_to_naira_words(amount):
    """
    Converts a decimal or integer amount to Nigerian Naira in words.
    Example: 185000 -> 'One Hundred and Eighty-Five Thousand Naira Only'
    """
    if amount is None or amount == 0:
        return "Zero Naira Only"

    units = ["", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine",
             "Ten", "Eleven", "Twelve", "Thirteen", "Fourteen", "Fifteen", "Sixteen",
             "Seventeen", "Eighteen", "Nineteen"]
    tens = ["", "", "Twenty", "Thirty", "Forty", "Fifty", "Sixty", "Seventy", "Eighty", "Ninety"]

    def _convert_hundreds(n):
        res = []
        if n >= 100:
            res.append(units[n // 100] + " Hundred")
            n %= 100
            if n > 0:
                res.append("and")
        if 0 < n < 20:
            res.append(units[n])
        elif n >= 20:
            t = tens[n // 10]
            u = units[n % 10]
            res.append(f"{t}-{u}" if u else t)
        return " ".join(res)

    int_part = int(amount)
    kobo_part = int(round((float(amount) - int_part) * 100))

    parts = []
    billions = int_part // 1000000000
    int_part %= 1000000000
    millions = int_part // 1000000
    int_part %= 1000000
    thousands = int_part // 1000
    remainder = int_part % 1000

    if billions > 0:
        parts.append(_convert_hundreds(billions) + " Billion")
    if millions > 0:
        parts.append(_convert_hundreds(millions) + " Million")
    if thousands > 0:
        parts.append(_convert_hundreds(thousands) + " Thousand")
    if remainder > 0:
        parts.append(_convert_hundreds(remainder))

    words = " ".join(parts).strip() if parts else "Zero"
    result = f"{words} Naira"
    if kobo_part > 0:
        kobo_words = _convert_hundreds(kobo_part)
        result += f", {kobo_words} Kobo"
    result += " Only"
    return result


class FraudReport(models.Model):
    public_id = models.UUIDField(
        default=uuid.uuid4,
        editable=False,
        unique=True,
        db_index=True,
        help_text="Public-facing report identifier — never expose the integer PK"
    )
    STATES = (
        ('submitted', 'Submitted'),
        ('under_review', 'Under Review'),
        ('published', 'Published'),
        ('disputed', 'Disputed'),
        ('resolved', 'Resolved'),
        ('rejected', 'Rejected'),
        ('restricted', 'Restricted'),
        ('archived', 'Archived'),
    )

    reference_number = models.CharField(
        max_length=50,
        unique=True,
        db_index=True,
        default='VNG-PENDING',
        help_text="Public reference tracking ID generated by service layer"
    )
    reporter = models.ForeignKey(
        User,
        on_delete=models.SET_NULL,
        null=True,
        related_name='submitted_reports'
    )
    target_subject = models.ForeignKey(
        SubjectEntity,
        on_delete=models.PROTECT,
        related_name='reports'
    )
    title = models.CharField(
        max_length=255,
        default='Allegation Report'
    )
    allegation = models.TextField(
        help_text="Detailed description of alleged incident"
    )
    amount_lost = models.DecimalField(
        max_digits=14,
        decimal_places=2,
        null=True,
        blank=True,
        help_text="Total financial amount lost in Naira (₦)"
    )
    incident_date = models.DateField(
        null=True,
        blank=True
    )
    state = models.CharField(
        max_length=20,
        choices=STATES,
        default='submitted',
        db_index=True
    )
    moderation_notes = models.TextField(
        blank=True,
        help_text="Internal moderation data; must not be exposed in public API responses"
    )
    created_at = models.DateTimeField(
        default=timezone.now
    )
    updated_at = models.DateTimeField(
        auto_now=True
    )

    class Meta:
        verbose_name = 'Fraud Report'
        verbose_name_plural = 'Fraud Reports'
        ordering = ['-created_at']

    def __str__(self):
        return f"[{self.reference_number}] {self.title} - {self.get_state_display()}"

    @property
    def is_misconduct(self):
        title_str = self.title or ''
        allegation_str = self.allegation or ''
        return (
            title_str.startswith('Staff Misconduct') or
            allegation_str.startswith('WORKPLACE MISCONDUCT REPORT')
        )

    @property
    def suspect_context(self):
        """Extracts submitted suspect context from the initial audit log."""
        if not self.pk:
            return {}
        init_log = self.audit_logs.filter(action="REPORT_SUBMITTED").first()
        if init_log and isinstance(init_log.details, dict):
            return init_log.details.get('suspect_context', {})
        return {}

    @property
    def amount_lost_formatted(self):
        """Returns formatted currency string, e.g. ₦185,000.00"""
        if self.amount_lost is not None:
            return f"₦{self.amount_lost:,.2f}"
        ctx_amount = self.suspect_context.get('amount_lost')
        if ctx_amount:
            try:
                from decimal import Decimal
                return f"₦{Decimal(str(ctx_amount)):,.2f}"
            except Exception:
                return str(ctx_amount)
        return "Not specified"

    @property
    def amount_lost_in_words(self):
        """Returns amount in Nigerian Naira words, e.g. 'One Hundred and Eighty-Five Thousand Naira Only'"""
        val = self.amount_lost
        if val is None:
            ctx_amount = self.suspect_context.get('amount_lost')
            if ctx_amount:
                try:
                    from decimal import Decimal
                    val = Decimal(str(ctx_amount))
                except Exception:
                    pass
        if val is None:
            return "Amount Not Specified"
        return number_to_naira_words(val)

    @property
    def suspect_email(self):
        """Returns the email address of the accused person or entity."""
        ctx = self.suspect_context
        if ctx.get('email'):
            return ctx['email']
        if hasattr(self.target_subject, 'business_profile') and self.target_subject.business_profile.contact_email:
            return self.target_subject.business_profile.contact_email
        return None

    @property
    def suspect_phone(self):
        """Returns the phone number of the accused person or entity."""
        ctx = self.suspect_context
        if ctx.get('phone'):
            return ctx['phone']
        if hasattr(self.target_subject, 'business_profile') and self.target_subject.business_profile.contact_phone:
            return self.target_subject.business_profile.contact_phone
        return None

    @property
    def suspect_bank_account(self):
        """Returns the bank account number of the accused entity."""
        ctx = self.suspect_context
        return ctx.get('bank_account') or None

    @property
    def suspect_bank_name(self):
        """Returns the bank name of the accused entity."""
        ctx = self.suspect_context
        return ctx.get('bank_name') or None

    @property
    def suspect_bank_account_name(self):
        """Returns the verified NIBSS/Paystack resolved account holder name, if available."""
        ctx = self.suspect_context
        return ctx.get('bank_account_name') or None

    @property
    def masked_bank_account(self):
        """
        NDPA 2023 & African Data Protection compliant masking for public interfaces.
        E.g. '0123456789' -> '012****789'
        """
        acct = self.suspect_bank_account
        if not acct:
            return ""
        val = str(acct).strip()
        if len(val) <= 4:
            return val
        if len(val) == 10:
            return f"{val[:3]}****{val[-3:]}"
        return f"{val[:2]}****{val[-2:]}"

    @property
    def masked_phone(self):
        """
        NDPA 2023 & African Data Protection compliant phone masking for public views.
        E.g. '08012345678' -> '0801***5678' or '+234801***5678'
        """
        ph = self.suspect_phone
        if not ph:
            return ""
        val = str(ph).strip()
        if len(val) <= 5:
            return val
        if len(val) >= 11:
            return f"{val[:4]}***{val[-4:]}"
        return f"{val[:3]}***{val[-2:]}"

    @property
    def whatsapp_clean_phone(self):
        """
        Returns the suspect phone normalized to E.164 digits without '+' for WhatsApp wa.me links.
        E.g. '08012345678' -> '2348012345678', '+2348012345678' -> '2348012345678'
        """
        ph = self.suspect_phone
        if not ph:
            return ""
        import re
        digits = re.sub(r'\D', '', str(ph))
        if not digits:
            return ""
        if digits.startswith('0') and len(digits) == 11:
            digits = '234' + digits[1:]
        elif len(digits) == 10 and digits[0] in ('7', '8', '9'):
            digits = '234' + digits
        return digits

    @property
    def whatsapp_due_process_url(self):
        """
        Generates a 1-click WhatsApp due-process dispatch link for moderators.
        Opens WhatsApp Web pre-loaded with the statutory 7-day fair-hearing notice,
        incident reference, loss amount, and direct dispute filing link.
        """
        phone = self.whatsapp_clean_phone
        if not phone:
            return ""

        from core.site_utils import get_dynamic_base_url
        import urllib.parse

        base_url = get_dynamic_base_url().rstrip('/')
        dispute_url = f"{base_url}/reports/{self.reference_number}/dispute/"

        target_name = ""
        if hasattr(self, 'target_subject') and self.target_subject and self.target_subject.name:
            target_name = self.target_subject.name
        else:
            target_name = "Account Holder"

        amount_str = self.amount_lost_formatted or "Unspecified"
        deadline_str = self.dispute_deadline or "7 days from filing"

        msg = (
            f"⚖️ *OFFICIAL NOTICE: FAIR HEARING & RIGHT OF RESPONSE*\n"
            f"*VerifyNG Public Trust & Safety Registry*\n\n"
            f"*Reference:* #{self.reference_number}\n"
            f"*Accused Party:* {target_name}\n"
            f"*Allegation Summary:* {self.title}\n"
            f"*Claimed Amount:* {amount_str}\n"
            f"*Due-Process Response Window:* 7 Calendar Days (Expires {deadline_str})\n\n"
            f"Hello,\n\n"
            f"A formal incident complaint has been lodged against your account/business on the VerifyNG National Trust Registry.\n\n"
            f"Under VerifyNG Fair Hearing and Statutory Due-Process guidelines, you are entitled to review the complaint, submit your formal defense statement, and upload counter-evidence (receipts, delivery notes, or proof of resolution) before moderation concludes.\n\n"
            f"👉 *Submit Your Statement & Counter-Evidence Here:*\n"
            f"{dispute_url}\n\n"
            f"*Note:* If no response is received by {deadline_str}, the investigation will conclude based strictly on the evidence submitted by the complainant, which may affect your public trust standing.\n\n"
            f"VerifyNG Compliance & Dispute Resolution Desk\n"
            f"support@verifyng.com | www.verifyng.com"
        )

        encoded_msg = urllib.parse.quote(msg)
        return f"https://wa.me/{phone}?text={encoded_msg}"

    @property
    def masked_nin(self):
        """
        Masked National Identification Number (NIN / National ID) for public views.
        E.g. '12345678901' -> '1234****901'
        """
        ctx = self.suspect_context
        nin = ctx.get('nin') or ctx.get('id_number')
        if not nin and hasattr(self.reporter, 'id_number'):
            nin = self.reporter.id_number
        if not nin:
            return ""
        val = str(nin).strip()
        if len(val) <= 4:
            return val
        return f"{val[:4]}****{val[-3:]}"

    @property
    def dispute_deadline(self):
        """The 7-day fair-hearing / right-of-response expiration date."""
        ctx = self.suspect_context
        if ctx.get('dispute_deadline'):
            return ctx['dispute_deadline']
        base_time = self.created_at or timezone.now()
        return (base_time + timedelta(days=7)).strftime('%d %B %Y')

    @property
    def is_within_dispute_window(self):
        """Returns True if within the 7-day fair-hearing window."""
        base_time = self.created_at or timezone.now()
        return timezone.now() <= (base_time + timedelta(days=7))

    @property
    def complainant_rebuttal(self):
        """Returns the formal rebuttal statement and evidence submitted by the complainant, if any."""
        if not self.pk:
            return None
        log = self.audit_logs.filter(action="COMPLAINANT_REBUTTAL_SUBMITTED").first()
        if log and isinstance(log.details, dict):
            details_dict = dict(log.details)
            return {
                'statement': log.details.get('rebuttal_statement', ''),
                'rebuttal_statement': log.details.get('rebuttal_statement', ''),
                'submitted_at': log.timestamp,
                'timestamp': log.timestamp,
                'evidence_id': log.details.get('evidence_id'),
                'evidence_name': log.details.get('evidence_name', ''),
                'actor': log.performed_by,
                'details': details_dict,
                'log': log,
            }
        return None

    @property
    def can_submit_rebuttal(self):
        """Returns True if complainant can submit their 1-time rebuttal."""
        return (
            self.state == 'disputed'
            and self.disputes.exists()
            and self.complainant_rebuttal is None
        )

    @property
    def are_pleadings_closed(self):
        """Pleadings close when complainant submits final rebuttal or report reaches final decision."""
        return self.complainant_rebuttal is not None or self.state in ('resolved', 'dismissed', 'closed', 'rejected')

    @property
    def moderator_info_requests(self):
        """Returns all interlocutory information requests issued by compliance moderators."""
        if not self.pk:
            return []
        return self.audit_logs.filter(action="MODERATOR_INFO_REQUEST").order_by('-timestamp')

    def pending_info_request_for_user(self, user):
        """Checks if a specific user has an active, unfulfilled info request."""
        if not user or not user.is_authenticated or not self.pk:
            return None
        is_reporter = (self.reporter_id == user.id)
        is_respondent = self.disputes.filter(disputant=user).exists()
        if not is_respondent and self.suspect_email and user.email:
            is_respondent = (self.suspect_email.strip().lower() == user.email.strip().lower())

        for req in self.moderator_info_requests:
            details = req.details or {}
            if details.get('status') == 'pending':
                target_role = details.get('target_role')
                if (target_role == 'complainant' and is_reporter) or (target_role == 'respondent' and is_respondent):
                    return req
        return None

    @property
    def active_dossier(self):
        """Returns the verified dossier if paid, or the latest pending dossier."""
        if not self.pk:
            return None
        verified = self.dossiers.filter(payment_status='verified').first()
        if verified:
            return verified
        return self.dossiers.first()

    @property
    def has_unlocked_dossier(self):
        if not self.pk:
            return False
        return self.dossiers.filter(payment_status='verified').exists()

    @property
    def has_evidence_and_amount(self):
        """Validates whether report has both an amount lost and at least one evidence file."""
        has_amount = bool(self.amount_lost or (self.suspect_context and self.suspect_context.get('amount_lost')))
        has_evidence = self.evidence_files.exists()
        return has_amount and has_evidence


class ReportEvidence(models.Model):
    EVIDENCE_TYPES = (
        ('document', 'Document/PDF'),
        ('screenshot', 'Screenshot/Image'),
        ('receipt', 'Payment Receipt'),
        ('chat_log', 'Chat Log'),
        ('other', 'Other Evidence'),
    )

    report = models.ForeignKey(
        FraudReport,
        on_delete=models.PROTECT,
        related_name='evidence_files'
    )
    file = models.FileField(
        upload_to='evidence/%Y/%m/',
        help_text="Evidence file; security/privacy controls applied in Phase 5"
    )
    file_type = models.CharField(
        max_length=20,
        choices=EVIDENCE_TYPES,
        default='screenshot'
    )
    description = models.CharField(
        max_length=255,
        blank=True
    )
    is_confidential = models.BooleanField(
        default=True,
        help_text="Confidential evidence accessible only to authorized moderators"
    )
    storage_provider = models.CharField(
        max_length=50,
        default='local',
        blank=True,
        help_text="Storage provider identifier ('local', 'cloudinary', 's3')"
    )
    storage_public_id = models.CharField(
        max_length=255,
        blank=True,
        help_text="Cloud provider public ID / storage key"
    )
    storage_resource_type = models.CharField(
        max_length=20,
        blank=True,
        help_text="Cloud provider resource type ('image', 'raw')"
    )
    storage_format = models.CharField(
        max_length=20,
        blank=True,
        help_text="File extension / format ('pdf', 'png', 'docx')"
    )
    uploaded_at = models.DateTimeField(
        default=timezone.now
    )

    class Meta:
        verbose_name = 'Report Evidence'
        verbose_name_plural = 'Report Evidence'

    def __str__(self):
        return f"Evidence ({self.get_file_type_display()}) for {self.report.reference_number}"

    @property
    def file_extension(self):
        """Returns lowercased file extension without leading dot."""
        if self.storage_format:
            return self.storage_format.lower().lstrip('.')
        if self.file and hasattr(self.file, 'name') and self.file.name:
            import os
            _, ext = os.path.splitext(self.file.name)
            return ext.lower().lstrip('.')
        return ''

    @property
    def is_image(self):
        return self.file_extension in ['png', 'jpg', 'jpeg', 'webp', 'gif', 'bmp']

    @property
    def is_pdf(self):
        return self.file_extension == 'pdf'

    @property
    def is_word_doc(self):
        return self.file_extension in ['doc', 'docx', 'rtf', 'odt']

    @property
    def filename(self):
        if self.file and hasattr(self.file, 'name') and self.file.name:
            import os
            return os.path.basename(self.file.name)
        return ''

    @property
    def secure_url(self):
        """
        Returns a direct viewable URL. For Cloudinary / cloud storage,
        generates an authorized signed URL. For local files, returns the file.url.
        """
        if self.storage_provider and self.storage_provider != 'local':
            try:
                from reports.storage_services import get_storage_service_for_provider
                storage = get_storage_service_for_provider(self.storage_provider)
                return storage.generate_signed_url(
                    public_id=self.storage_public_id,
                    format=self.storage_format,
                    resource_type=self.storage_resource_type or 'image',
                    expires_in_seconds=3600
                )
            except Exception:
                pass
        if self.file and hasattr(self.file, 'url'):
            return self.file.url
        return ''


