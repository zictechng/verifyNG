def generate_certificate_id():
    """
    Generates a non-sequential, non-guessable certificate ID.
    Format: VNG-{YEAR}-{8 uppercase hex chars}
    Example: VNG-2026-A7F2B9C1
    """
    year = tz.now().year
    hex_part = secrets.token_hex(4).upper()
    return f"VNG-{year}-{hex_part}"


class VerificationCertificate(models.Model):
    """
    Issued to a person who has applied and passed identity verification.
    This is the permanent, queryable trust profile for an individual.
    Never delete — revoke or suspend instead.
    """

    CHECK_LEVEL_CHOICES = (
        ('employment', 'Employment Check'),   # Level 2
        ('enhanced', 'Enhanced Check'),       # Level 3
    )

    STATUS_CHOICES = (
        ('pending',    'Pending — awaiting NIN verification'),
        ('active',     'Active'),
        ('suspended',  'Suspended'),
        ('revoked',    'Revoked'),
        ('expired',    'Expired'),
    )

    certificate_id = models.CharField(
        max_length=20,
        unique=True,
        db_index=True,
        default=generate_certificate_id,
        help_text="Public certificate reference. Format: VNG-YYYY-XXXXXXXX"
    )
    subject = models.ForeignKey(
        'identities.SubjectEntity',
        on_delete=models.PROTECT,
        related_name='certificates',
        help_text="The person this certificate belongs to"
    )
    holder = models.ForeignKey(
        'users.User',
        on_delete=models.PROTECT,
        related_name='held_certificates',
        help_text="The VerifyNG account that applied for this certificate"
    )
    check_level = models.CharField(
        max_length=20,
        choices=CHECK_LEVEL_CHOICES,
        default='employment',
        db_index=True
    )
    status = models.CharField(
        max_length=20,
        choices=STATUS_CHOICES,
        default='pending',
        db_index=True
    )
    issued_at = models.DateTimeField(
        null=True,
        blank=True,
        help_text="Set when status moves to active"
    )
    expires_at = models.DateTimeField(
        null=True,
        blank=True,
        help_text="2 years for Employment Check, 3 years for Enhanced Check"
    )
    revoked_at = models.DateTimeField(null=True, blank=True)
    revocation_reason = models.TextField(blank=True)
    suspended_at = models.DateTimeField(null=True, blank=True)
    suspension_reason = models.TextField(blank=True)
    qr_code_url = models.CharField(
        max_length=500,
        blank=True,
        help_text="S3 path to the QR code image"
    )
    pdf_file = models.FileField(
        upload_to='certificates/pdf/',
        blank=True,
        null=True,
        help_text="Private S3 — served via pre-signed URL only"
    )
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)
    is_active = models.BooleanField(default=True)

    class Meta:
        verbose_name = 'Verification Certificate'
        verbose_name_plural = 'Verification Certificates'
        ordering = ['-created_at']
        indexes = [
            models.Index(fields=['certificate_id']),
            models.Index(fields=['status', 'check_level']),
            models.Index(fields=['holder', 'status']),
        ]

    def __str__(self):
        return f"{self.certificate_id} — {self.holder} ({self.get_status_display()})"

    @property
    def is_valid(self):
        """Returns True only if certificate is active and not expired."""
        if self.status != 'active':
            return False
        if self.expires_at and tz.now() > self.expires_at:
            return False
        return True

    @property
    def expiry_years(self):
        """Validity period based on check level."""
        return 3 if self.check_level == 'enhanced' else 2

    def activate(self):
        """
        Move certificate from pending to active.
        Sets issued_at and calculates expires_at.
        Call this from the service layer after NIN verification passes.
        """
        from datetime import timedelta
        now = tz.now()
        self.status = 'active'
        self.issued_at = now
        self.expires_at = now + timedelta(days=365 * self.expiry_years)
        self.save(update_fields=['status', 'issued_at', 'expires_at', 'updated_at'])

    def suspend(self, reason=''):
        self.status = 'suspended'
        self.suspended_at = tz.now()
        self.suspension_reason = reason
        self.save(update_fields=['status', 'suspended_at', 'suspension_reason', 'updated_at'])

    def revoke(self, reason=''):
        self.status = 'revoked'
        self.revoked_at = tz.now()
        self.revocation_reason = reason
        self.save(update_fields=['status', 'revoked_at', 'revocation_reason', 'updated_at'])


