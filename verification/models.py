from django.db import models
from django.utils import timezone
from users.models import User
from identities.models import SubjectEntity


class VerificationRequest(models.Model):
    VERIFICATION_TYPES = (
        ('identity', 'Identity Verification'),
        ('employment', 'Employment Verification'),
        ('address', 'Address Verification'),
        ('credential', 'Credential Verification'),
        ('full_check', 'Full Background Check'),
    )

    STATUS_CHOICES = (
        ('pending', 'Pending'),
        ('in_progress', 'In Progress'),
        ('completed', 'Completed'),
        ('rejected', 'Rejected'),
        ('expired', 'Expired'),
    )

    reference_number = models.CharField(
        max_length=50,
        unique=True,
        db_index=True,
        help_text="Public verification reference ID generated by service layer"
    )
    requester = models.ForeignKey(
        User,
        on_delete=models.SET_NULL,
        null=True,
        related_name='submitted_verifications'
    )
    target_subject = models.ForeignKey(
        SubjectEntity,
        on_delete=models.PROTECT,
        related_name='verification_requests'
    )
    verification_type = models.CharField(
        max_length=20,
        choices=VERIFICATION_TYPES,
        default='identity'
    )
    status = models.CharField(
        max_length=20,
        choices=STATUS_CHOICES,
        default='pending',
        db_index=True
    )
    notes = models.TextField(
        blank=True,
        help_text="Internal notes for verification officer"
    )
    created_at = models.DateTimeField(
        default=timezone.now
    )
    updated_at = models.DateTimeField(
        auto_now=True
    )

    class Meta:
        verbose_name = 'Verification Request'
        verbose_name_plural = 'Verification Requests'
        ordering = ['-created_at']

    def __str__(self):
        return f"[{self.reference_number}] {self.get_verification_type_display()} - {self.get_status_display()}"


class VerificationResult(models.Model):
    OUTCOME_CHOICES = (
        ('verified', 'Verified'),
        ('unverified', 'Unverified'),
        ('inconclusive', 'Inconclusive'),
        ('flagged', 'Flagged for Review'),
    )

    request = models.OneToOneField(
        VerificationRequest,
        on_delete=models.PROTECT,
        related_name='result'
    )
    verified_by = models.ForeignKey(
        User,
        on_delete=models.SET_NULL,
        null=True,
        help_text="Verification officer or system handler"
    )
    outcome = models.CharField(
        max_length=20,
        choices=OUTCOME_CHOICES,
        db_index=True
    )
    summary = models.TextField(
        help_text="Summary of verification findings"
    )
    details = models.JSONField(
        default=dict,
        blank=True,
        help_text="Structured factual breakdown of verification indicators"
    )
    verified_at = models.DateTimeField(
        default=timezone.now
    )

    class Meta:
        verbose_name = 'Verification Result'
        verbose_name_plural = 'Verification Results'
        ordering = ['-verified_at']

    def __str__(self):
        return f"Result: {self.get_outcome_display()} for {self.request.reference_number}"
