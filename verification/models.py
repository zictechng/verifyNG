class VerificationRequest(models.Model):
    public_id = models.UUIDField(
        default=uuid.uuid4,
        editable=False,
        unique=True,
        db_index=True,
        help_text="Public-facing verification request identifier — never expose the integer PK"
    )
    VERIFICATION_TYPES = (
        ('property', 'Property, Land & Real Estate Due Diligence'),
        ('vehicle', 'Vehicle & Automobile Ownership Verification'),
        ('credential', 'Academic & Qualification Certificate'),
        ('business', 'Business & Corporate Registration (CAC)'),
        ('contract', 'Deal, Contract & Investment Vetting'),
        ('identity', 'Identity & Background Check'),
        ('employment', 'Employment & Workplace Record'),
        ('address', 'Physical Address Verification'),
        ('full_check', 'Full Comprehensive Due Diligence'),
    )

    STATUS_CHOICES = (
        ('pending', 'Pending'),
        ('pending_payment', 'Pending Payment'),
        ('in_progress', 'In Progress'),
        ('completed', 'Completed'),
        ('rejected', 'Rejected'),
        ('expired', 'Expired'),
    )

    reference_number = models.CharField(
        max_length=50,
        unique=True,
        db_index=True,
        help_text="Public verification reference ID generated by service layer"
    )
    requester = models.ForeignKey(
        User,
        on_delete=models.SET_NULL,
        null=True,
        related_name='submitted_verifications'
    )
    target_subject = models.ForeignKey(
        SubjectEntity,
        on_delete=models.PROTECT,
        related_name='verification_requests'
    )
    verification_type = models.CharField(
        max_length=20,
        choices=VERIFICATION_TYPES,
        default='identity'
    )
    status = models.CharField(
        max_length=20,
        choices=STATUS_CHOICES,
        default='pending',
        db_index=True
    )
    user_requirements = models.TextField(
        blank=True,
        default='',
        help_text="Context and verification requirements submitted by the applicant"
    )
    document = models.FileField(
        upload_to='verification_docs/%Y/%m/',
        blank=True,
        null=True,
        help_text="Primary supporting document uploaded by applicant"
    )
    notes = models.TextField(
        blank=True,
        help_text="Internal notes for verification officer"
    )
    created_at = models.DateTimeField(
        default=timezone.now
    )
    updated_at = models.DateTimeField(
        auto_now=True
    )

    class Meta:
        verbose_name = 'Verification Request'
        verbose_name_plural = 'Verification Requests'
        ordering = ['-created_at']

    @property
    def has_documents(self):
        try:
            for doc in self.documents.all():
                if doc.file_exists:
                    return True
            if self.document and self.document.name and self.document.storage.exists(self.document.name):
                return True
        except Exception:
            pass
        return False

    @property
    def primary_document(self):
        first_doc = self.documents.first()
        if first_doc:
            return first_doc
        return None

    def __str__(self):
        return f"[{self.reference_number}] {self.get_verification_type_display()} - {self.get_status_display()}"


