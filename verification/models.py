class VerificationDocument(models.Model):
    verification = models.ForeignKey(
        VerificationRequest,
        on_delete=models.CASCADE,
        related_name='documents'
    )
    file = models.FileField(
        upload_to='verification_docs/%Y/%m/',
        help_text="Supporting verification document or proof"
    )
    document_name = models.CharField(
        max_length=255,
        blank=True
    )
    file_size = models.PositiveIntegerField(
        default=0,
        help_text="File size in bytes"
    )
    uploaded_at = models.DateTimeField(
        default=timezone.now
    )

    class Meta:
        verbose_name = 'Verification Document'
        verbose_name_plural = 'Verification Documents'
        ordering = ['uploaded_at']

    def __str__(self):
        return f"{self.document_name or self.file.name} [{self.verification.reference_number}]"

    @property
    def file_extension(self):
        if self.file and self.file.name:
            return os.path.splitext(self.file.name)[1].lower()
        return ''

    @property
    def is_image(self):
        return self.file_extension in ['.png', '.jpg', '.jpeg', '.webp']

    @property
    def is_pdf(self):
        return self.file_extension == '.pdf'

    @property
    def file_exists(self):
        try:
            return bool(self.file and self.file.name and self.file.storage.exists(self.file.name))
        except Exception:
            return False

    @property
    def formatted_size(self):
        if not self.file_size:
            if self.file:
                try:
                    size = self.file.size
                    if size < 1024 * 1024:
                        return f"{round(size / 1024, 1)} KB"
                    return f"{round(size / (1024 * 1024), 2)} MB"
                except Exception:
                    pass
            return "0 KB"
        if self.file_size < 1024 * 1024:
            return f"{round(self.file_size / 1024, 1)} KB"
        return f"{round(self.file_size / (1024 * 1024), 2)} MB"
